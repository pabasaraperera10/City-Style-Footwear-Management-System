    private void btnCalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalculateActionPerformed
         double price = Double.parseDouble(txtCurrentPrice.getText());
    double discount = Double.parseDouble(txtDiscount.getText());

    double newPrice = price - (price * discount / 100);

    txtBuckPrice.setText(String.valueOf(newPrice));


    }//GEN-LAST:event_btnCalculateActionPerformed

    private void btnApplyDiscountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnApplyDiscountActionPerformed
         try {

        double newPrice = Double.parseDouble(txtBuckPrice.getText());

        ShoeClass shoe = new ShoeClass();

         PreparedStatement ps = shoe.getConnection().prepareStatement(
            "UPDATE ShoeTable SET Price=? WHERE ShoeId=?");

        ps.setDouble(1,newPrice);
        ps.setString(2,cmbShoeId.getSelectedItem().toString());

        ps.executeUpdate();

        txtCurrentPrice.setText(String.valueOf(newPrice));

    } catch(Exception e) {

        System.out.println("Price update error " + e);
    } 

    }//GEN-LAST:event_btnApplyDiscountActionPerformed

