    private void cmbShoeIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbShoeIdActionPerformed
       try {

        ShoeClass shoe = new ShoeClass();

        ResultSet rs = shoe.SearchShoes(cmbShoeId.getSelectedItem().toString());

        if(rs.next())
        {
            txtCurrentPrice.setText(rs.getString("Price"));
        }

    } catch(Exception e) {

        System.out.println("Price load error " + e);
    }
    }//GEN-LAST:event_cmbShoeIdActionPerformed

